// Deterministic PRNG so historical candles are realistic, smooth, and reproducible
function mulberry32(seed: number) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function hashSymbol(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/**
 * Generates realistic OHLCV series ending right at `currentPrice` for 1D, 1W, 1M, 1Y, 5Y.
 */
export function generateHistoricalCandles(
  stock: StockSeed,
  timeframe: TimeframeKey,
  currentPrice: number
): OhlcvBar[] {
  const tfConfig: Record<TimeframeKey, { count: number; stepSec: number; barVolScale: number }> = {
    '1D': { count: 78, stepSec: 300, barVolScale: 0.0028 }, // 5-min bars
    '1W': { count: 95, stepSec: 1800, barVolScale: 0.0055 }, // 30-min bars
    '1M': { count: 65, stepSec: 14400, barVolScale: 0.0095 }, // 4-hour / session bars
    '1Y': { count: 252, stepSec: 86400, barVolScale: 0.0155 }, // 1-day bars
    '5Y': { count: 260, stepSec: 604800, barVolScale: 0.032 }, // 1-week bars
  };

  const { count, stepSec, barVolScale } = tfConfig[timeframe];
  const rng = mulberry32(hashSymbol(`${stock.symbol}:${timeframe}`));
  const volFactor = (stock.annualVolatility / 0.21) * barVolScale;

  // Build relative log returns first, then anchor the final close to `currentPrice`
  const returns: number[] = [];
  const drift = timeframe === '5Y' ? 0.0024 : timeframe === '1Y' ? 0.00055 : 0.00012;
  for (let i = 0; i < count; i++) {
    // Box-Muller normal approx
    const u1 = Math.max(1e-6, rng());
    const u2 = rng();
    const z = Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
    returns.push(drift + z * volFactor);
  }

  const prices: number[] = new Array(count);
  prices[count - 1] = currentPrice;
  for (let i = count - 2; i >= 0; i--) {
    prices[i] = Math.max(10, prices[i + 1] / Math.exp(returns[i + 1]));
  }

  const nowSec = Math.floor(Date.now() / 1000);
  const alignedNow = Math.floor(nowSec / stepSec) * stepSec;
  const baseVol = Math.round((stock.marketCapCr / Math.max(100, stock.basePrice)) * 950);

  const candles: OhlcvBar[] = [];
  for (let i = 0; i < count; i++) {
    const close = Number(prices[i].toFixed(2));
    const prev = i === 0 ? Number((close * (1 - returns[0] * 0.6)).toFixed(2)) : candles[i - 1].close;
    const open = prev;
    const intraSpread = Math.abs(close - open) + close * volFactor * (0.35 + rng() * 0.85);
    const high = Number((Math.max(open, close) + intraSpread * (0.25 + rng() * 0.55)).toFixed(2));
    const low = Number(Math.max(1, Math.min(open, close) - intraSpread * (0.25 + rng() * 0.55)).toFixed(2));
    const activity = 0.55 + rng() * 1.15 + (Math.abs(close - open) / Math.max(1, open)) * 35;
    const volume = Math.max(1200, Math.round(baseVol * activity * (stepSec >= 86400 ? 1 : 0.08)));

    candles.push({
      time: alignedNow - (count - 1 - i) * stepSec,
      open,
      high,
      low,
      close,
      volume,
    });
  }

  return candles;
}
